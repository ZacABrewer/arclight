#!/usr/bin/env node
// Copies the repository's user-facing Markdown docs (docs/**) into the Starlight content
// collection at site/src/content/docs/docs/, so every page is served under /docs/...
//
// For each page it:
//   - adds Starlight frontmatter (title from the first "# " heading, which is removed from the
//     body; description from the first paragraph; editUrl pointing at the source file on GitHub);
//   - rewrites relative links between docs to site URLs (lowercase slugs, anchors kept);
//   - rewrites links to other repository files to their GitHub URL;
//   - copies images the page references;
//   - collects broken internal links and exits non-zero if there are any.
//
// The docs in the repository stay the single source of truth; the output folder is git-ignored.

import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync, copyFileSync } from 'node:fs';
import { dirname, join, posix, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import GithubSlugger from 'github-slugger';

const here = dirname(fileURLToPath(import.meta.url));
const SITE = resolve(here, '..');
const REPO = resolve(SITE, '..');
const DOCS = join(REPO, 'docs');
const OUT = join(SITE, 'src', 'content', 'docs', 'docs');
const GITHUB = 'https://github.com/ZacABrewer/arclight';
const URL_PREFIX = '/docs';

// Folders and files under docs/ that are internal working notes rather than user documentation.
// Links to them from published pages go to GitHub instead.
const EXCLUDE_DIRS = new Set(['design']);
const EXCLUDE_FILES = new Set(['UI-INVENTORY.md']);

// Sidebar order inside autogenerated groups (lower first). Unlisted pages come after, A-Z.
const ORDER = {
  'getting-started/requirements.md': 1,
  'getting-started/install-other-platforms.md': 2,
  'getting-started/install-docker.md': 3,
  'getting-started/first-run-wizard.md': 40,
  'getting-started/folders-and-hardlinks.md': 41,
  'getting-started/migrating.md': 42,
  'getting-started/exposing-outside-home.md': 43,
  'getting-started/sub-path-hosting.md': 43.5,
  'getting-started/updating.md': 44,
  'getting-started/backup-restore.md': 45,
  'qa/README.md': 0,
};

const IMAGE_EXT = /\.(png|jpe?g|gif|svg|webp|avif)$/i;

/** posix path of a repo file, relative to the repo root */
const repoRel = (abs) => relative(REPO, abs).split(sep).join('/');

function walk(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const abs = join(dir, name);
    const st = statSync(abs);
    if (st.isDirectory()) {
      if (dir === DOCS && EXCLUDE_DIRS.has(name)) continue;
      out.push(...walk(abs));
    } else if (name.endsWith('.md')) {
      if (dir === DOCS && EXCLUDE_FILES.has(name)) continue;
      out.push(abs);
    }
  }
  return out;
}

/** docs/getting-started/Install-Docker.md -> getting-started/install-docker (slug, no extension) */
function slugOf(absDoc) {
  let rel = relative(DOCS, absDoc).split(sep).join('/').replace(/\.md$/i, '');
  rel = rel
    .split('/')
    .map((s) => s.toLowerCase())
    .join('/');
  if (rel === 'readme') return '';
  if (rel.endsWith('/readme')) return rel.slice(0, -'/readme'.length);
  return rel;
}

/** Output file for a doc: README.md becomes index.md of its folder. */
function outFileOf(absDoc) {
  const slug = slugOf(absDoc);
  if (slug === '') return join(OUT, 'index.md');
  const parts = slug.split('/');
  return isIndex(absDoc) ? join(OUT, ...parts, 'index.md') : join(OUT, ...parts.slice(0, -1), `${parts.at(-1)}.md`);
}
const isIndex = (absDoc) => /(^|[\\/])readme\.md$/i.test(absDoc);

const urlOf = (absDoc) => {
  const slug = slugOf(absDoc);
  return slug === '' ? `${URL_PREFIX}/` : `${URL_PREFIX}/${slug}/`;
};

/** Heading ids the way Starlight (github-slugger) generates them, plus explicit <a id> / id= anchors. */
function anchorsOf(markdown) {
  const slugger = new GithubSlugger();
  const ids = new Set();
  let fence = null;
  for (const line of markdown.split('\n')) {
    const f = line.match(/^\s*(```+|~~~+)/);
    if (f) {
      if (!fence) fence = f[1];
      else if (f[1].startsWith(fence[0]) && f[1].length >= fence.length) fence = null;
      continue;
    }
    if (fence) continue;
    const h = line.match(/^#{1,6}\s+(.*?)\s*#*\s*$/);
    if (h) ids.add(slugger.slug(plainText(h[1])));
    for (const m of line.matchAll(/\bid=["']([^"']+)["']/g)) ids.add(m[1]);
  }
  return ids;
}

/** Strip Markdown inline formatting for titles, descriptions and heading slugs. */
function plainText(s) {
  return s
    .replace(/!\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/\[([^\]]*)\]\[[^\]]*\]/g, '$1')
    .replace(/<[^>]+>/g, '')
    .replace(/`([^`]*)`/g, '$1')
    .replace(/(\*\*|__)(.*?)\1/g, '$2')
    .replace(/(^|\W)[*_]([^*_]+)[*_](?=\W|$)/g, '$1$2')
    .replace(/\s+/g, ' ')
    .trim();
}

function description(body) {
  const lines = body.split('\n');
  let i = 0;
  while (i < lines.length && lines[i].trim() === '') i++;
  const para = [];
  for (; i < lines.length && lines[i].trim() !== ''; i++) para.push(lines[i]);
  const first = para[0]?.trim() ?? '';
  if (!first || /^(\||```|~~~|#|<|-\s|\*\s|\d+\.\s)/.test(first)) return undefined;
  let text = plainText(para.join(' ').replace(/^>\s?/gm, ''));
  if (text.length > 220) {
    const cut = text.slice(0, 220);
    const stop = cut.lastIndexOf('. ');
    text = stop > 80 ? cut.slice(0, stop + 1) : `${cut.slice(0, cut.lastIndexOf(' '))}…`;
  }
  return text || undefined;
}

// ---------------------------------------------------------------------------------------------

if (!existsSync(DOCS)) {
  console.error(`sync-docs: ${DOCS} not found`);
  process.exit(1);
}

const files = walk(DOCS);
const published = new Map(files.map((f) => [resolve(f).toLowerCase(), f]));
const sources = new Map(files.map((f) => [f, readFileSync(f, 'utf8').replace(/\r\n/g, '\n')]));
const anchorCache = new Map();
const anchorsFor = (f) => {
  if (!anchorCache.has(f)) anchorCache.set(f, anchorsOf(sources.get(f)));
  return anchorCache.get(f);
};

const broken = [];
const anchorWarnings = [];
const images = new Set();

/** Rewrite one link target found in `fromAbs` on `line`. Returns the new target. */
function rewrite(target, fromAbs, lineNo) {
  if (!target || /^(?:[a-z][a-z0-9+.-]*:|#|\/\/|\/)/i.test(target)) {
    // external, mailto:, in-page anchor, protocol-relative or site-absolute: keep, but check
    // in-page anchors against this page's headings.
    if (target.startsWith('#') && target.length > 1 && !anchorsFor(fromAbs).has(decodeURIComponent(target.slice(1)))) {
      anchorWarnings.push(`${repoRel(fromAbs)}:${lineNo}  ${target}`);
    }
    return target;
  }
  const hashAt = target.indexOf('#');
  const pathPart = hashAt === -1 ? target : target.slice(0, hashAt);
  const anchor = hashAt === -1 ? '' : target.slice(hashAt);
  const queryless = pathPart.split('?')[0];
  let abs;
  try {
    abs = resolve(dirname(fromAbs), decodeURIComponent(queryless));
  } catch {
    abs = resolve(dirname(fromAbs), queryless);
  }
  const rel = repoRel(abs);
  if (rel.startsWith('..')) {
    broken.push(`${repoRel(fromAbs)}:${lineNo}  ${target}  (points outside the repository)`);
    return target;
  }

  // A published doc page.
  const doc = published.get(abs.toLowerCase());
  if (doc) {
    if (anchor.length > 1 && !anchorsFor(doc).has(decodeURIComponent(anchor.slice(1)))) {
      anchorWarnings.push(`${repoRel(fromAbs)}:${lineNo}  ${target}`);
    }
    return urlOf(doc) + anchor;
  }

  // An image next to the docs: copy it, keep the relative link.
  if (IMAGE_EXT.test(queryless) && rel.startsWith('docs/') && existsSync(abs)) {
    images.add(abs);
    return target;
  }

  if (!existsSync(abs)) {
    broken.push(`${repoRel(fromAbs)}:${lineNo}  ${target}  (${rel} does not exist)`);
    return target;
  }

  // Any other repository file or folder (source code, docker files, excluded notes, README, LICENSE).
  const kind = statSync(abs).isDirectory() ? 'tree' : 'blob';
  return `${GITHUB}/${kind}/main/${rel.split('/').map(encodeURIComponent).join('/')}${anchor}`;
}

/** Replace links outside code. */
function rewriteBody(body, fromAbs, lineOffset) {
  let fence = null;
  return body
    .split('\n')
    .map((line, idx) => {
      const lineNo = idx + 1 + lineOffset;
      const f = line.match(/^\s*(```+|~~~+)/);
      if (f) {
        if (!fence) fence = f[1];
        else if (f[1].startsWith(fence[0]) && f[1].length >= fence.length) fence = null;
        return line;
      }
      if (fence) return line;

      // Mask inline code so links shown as examples are left alone.
      const codes = [];
      let masked = line.replace(/(`+)[\s\S]*?\1/g, (m) => {
        codes.push(m);
        return `\u0000${codes.length - 1}\u0000`;
      });
      // Reference-style definitions: [id]: target "title"
      masked = masked.replace(/^(\s{0,3}\[[^\]]+\]:\s*)(<?)([^\s>]+)(>?)/, (_m, pre, lt, t, gt) => pre + lt + rewrite(t, fromAbs, lineNo) + gt);
      // Inline links and images: [text](target "title") / ![alt](target)
      masked = masked.replace(/(\]\()(<?)([^)\s>]+)(>?)((?:\s+(?:"[^"]*"|'[^']*'))?\))/g, (_m, open, lt, t, gt, close) => open + lt + rewrite(t, fromAbs, lineNo) + gt + close);
      // Raw HTML attributes
      masked = masked.replace(/\b(href|src)=(["'])([^"']+)\2/g, (_m, attr, q, t) => `${attr}=${q}${rewrite(t, fromAbs, lineNo)}${q}`);
      return masked.replace(/\u0000(\d+)\u0000/g, (_m, i) => codes[Number(i)]);
    })
    .join('\n');
}

rmSync(OUT, { recursive: true, force: true });
let pages = 0;

for (const file of files) {
  const raw = sources.get(file);
  const lines = raw.split('\n');
  const h1 = lines.findIndex((l) => /^#\s+\S/.test(l));
  let title;
  let bodyStart = 0;
  if (h1 !== -1) {
    title = plainText(lines[h1].replace(/^#\s+/, ''));
    bodyStart = h1 + 1;
  } else {
    title = slugOf(file).split('/').pop() || 'Documentation';
  }
  // Drop the H1 line but keep line positions so broken-link reports point at the right line.
  const bodyLines = h1 === -1 ? lines : lines.map((l, i) => (i === h1 ? '' : l));
  const rewritten = rewriteBody(bodyLines.join('\n'), file, 0).replace(/^\s+/, '');

  const rel = relative(DOCS, file).split(sep).join('/');
  const fm = ['---', `title: ${JSON.stringify(title)}`];
  const desc = description(lines.slice(bodyStart).join('\n'));
  if (desc) fm.push(`description: ${JSON.stringify(desc)}`);
  fm.push(`editUrl: ${JSON.stringify(`${GITHUB}/edit/main/docs/${rel}`)}`);
  if (rel in ORDER) fm.push('sidebar:', `  order: ${ORDER[rel]}`);
  if (slugOf(file) === '') fm.push('sidebar:', '  label: Overview');
  fm.push('---', '');

  const out = outFileOf(file);
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, `${fm.join('\n')}\n${rewritten.trimEnd()}\n`);
  pages++;
}

for (const img of images) {
  const rel = relative(DOCS, img);
  // Image paths keep their original case; page files are lowercased, folders too.
  const parts = rel.split(sep);
  const dest = join(OUT, ...parts.slice(0, -1).map((p) => p.toLowerCase()), parts.at(-1));
  mkdirSync(dirname(dest), { recursive: true });
  copyFileSync(img, dest);
}

if (anchorWarnings.length) {
  console.warn(`sync-docs: ${anchorWarnings.length} link(s) to a heading that was not found (warning only):`);
  for (const w of anchorWarnings) console.warn(`  ${w}`);
}
if (broken.length) {
  console.error(`sync-docs: ${broken.length} broken internal link(s):`);
  for (const b of broken) console.error(`  ${b}`);
  process.exit(1);
}
console.log(`sync-docs: ${pages} pages, ${images.size} images -> ${posix.join('src/content/docs/docs')}`);
