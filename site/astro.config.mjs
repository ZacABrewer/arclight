// @ts-check
import { existsSync, readdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import sitemap from '@astrojs/sitemap';
import starlight from '@astrojs/starlight';
import { defineConfig } from 'astro/config';

const SITE_DIR = dirname(fileURLToPath(import.meta.url));
const CONTENT = join(SITE_DIR, 'src', 'content', 'docs');
const DOCS = join(CONTENT, 'docs'); // generated by scripts/sync-docs.mjs
const LEGAL = join(CONTENT, 'legal');

/** Page slugs (without .md) present in a generated docs folder. */
const pagesIn = (dir) =>
  existsSync(dir)
    ? readdirSync(dir)
        .filter((f) => /\.mdx?$/.test(f) && !/^index\.mdx?$/.test(f))
        .map((f) => f.replace(/\.mdx?$/, ''))
        .sort()
    : [];
/** Only link root pages that exist, so a renamed doc never breaks the build. */
const rootPages = (...names) =>
  names.filter((n) => existsSync(join(DOCS, `${n}.md`))).map((n) => `docs/${n}`);

const gettingStarted = pagesIn(join(DOCS, 'getting-started'));
// Install guides first and in their own group: the platform chooser, the reference Docker
// install, then every other platform A-Z. New install-*.md files appear automatically.
const installFirst = ['install-other-platforms', 'install-docker'];
const installGuides = [
  ...installFirst.filter((p) => gettingStarted.includes(p)),
  ...gettingStarted.filter((p) => p.startsWith('install-') && !installFirst.includes(p)),
].map((p) => `docs/getting-started/${p}`);
const setupOrder = ['requirements', 'first-run-wizard', 'folders-and-hardlinks', 'migrating', 'exposing-outside-home', 'sub-path-hosting', 'updating', 'backup-restore'];
const setupPages = [
  ...setupOrder.filter((p) => gettingStarted.includes(p)),
  ...gettingStarted.filter((p) => !p.startsWith('install-') && !setupOrder.includes(p)),
].map((p) => `docs/getting-started/${p}`);

const hasLegal = existsSync(LEGAL) && readdirSync(LEGAL).some((f) => /\.mdx?$/.test(f));
const hasDir = (name) => existsSync(join(DOCS, name));

/** @type {any[]} */
const sidebar = [
  { label: 'Start here', items: [{ label: 'Documentation overview', link: '/docs/' }, ...rootPages('user-guide')] },
  { label: 'Install', items: installGuides },
  { label: 'Getting started', items: setupPages },
  hasDir('using') && { label: 'Using Arclight', collapsed: true, items: [{ autogenerate: { directory: 'docs/using' } }] },
  { label: 'Guides & operations', collapsed: true, items: rootPages('operations', 'remote-engine', 'cloudflare', 'themes') },
  {
    label: 'Troubleshooting & FAQ',
    items: [...rootPages('troubleshooting', 'faq'), ...(existsSync(join(DOCS, 'qa', '99-known-limitations.md')) ? ['docs/qa/99-known-limitations'] : [])],
  },
  {
    label: 'Reference',
    collapsed: true,
    items: [
      ...rootPages('api', 'glossary', 'architecture'),
      ...(hasDir('spec') ? [{ label: 'Specifications', collapsed: true, items: [{ autogenerate: { directory: 'docs/spec' } }] }] : []),
    ],
  },
  hasDir('mobile') && { label: 'Mobile apps', collapsed: true, items: [{ autogenerate: { directory: 'docs/mobile' } }] },
  { label: 'Contributing', collapsed: true, items: rootPages('developing', 'conventions', 'releasing', 'translating', 'roadmap') },
  hasDir('qa') && { label: 'QA checklists', collapsed: true, items: [{ autogenerate: { directory: 'docs/qa' } }] },
  hasLegal && { label: 'Legal', collapsed: true, items: [{ autogenerate: { directory: 'legal' } }] },
  { label: 'Support', link: '/support/' },
].filter(Boolean);

export default defineConfig({
  site: 'https://arclight.moviemethat.com',
  trailingSlash: 'ignore',
  integrations: [
    starlight({
      title: 'Arclight',
      description:
        'Self-hosted media automation in one app: requests, search, a built-in torrent engine, subtitles, music and audiobooks. A clean-room replacement for the *arr stack.',
      logo: {
        dark: './src/assets/lockup-dark.svg',
        light: './src/assets/lockup-light.svg',
        alt: 'Arclight',
        replacesTitle: true,
      },
      favicon: '/favicon.svg',
      social: [{ icon: 'github', label: 'GitHub', href: 'https://github.com/ZacABrewer/arclight' }],
      customCss: ['@fontsource/chakra-petch/700.css', './src/styles/arclight.css'],
      components: {
        Footer: './src/components/Footer.astro',
      },
      head: [
        { tag: 'link', attrs: { rel: 'icon', type: 'image/png', sizes: '32x32', href: '/favicon-32.png' } },
        { tag: 'link', attrs: { rel: 'apple-touch-icon', sizes: '180x180', href: '/apple-touch-icon.png' } },
        { tag: 'meta', attrs: { name: 'theme-color', content: '#02070a' } },
        { tag: 'meta', attrs: { property: 'og:image', content: 'https://arclight.moviemethat.com/og.png' } },
        { tag: 'meta', attrs: { property: 'og:image:width', content: '1200' } },
        { tag: 'meta', attrs: { property: 'og:image:height', content: '630' } },
        { tag: 'meta', attrs: { property: 'og:image:alt', content: 'Arclight: self-hosted media automation in one app' } },
        { tag: 'meta', attrs: { name: 'twitter:image', content: 'https://arclight.moviemethat.com/og.png' } },
      ],
      sidebar,
      lastUpdated: false,
      credits: false,
      tableOfContents: { minHeadingLevel: 2, maxHeadingLevel: 3 },
    }),
    sitemap(),
  ],
});
