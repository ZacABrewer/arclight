#!/usr/bin/env node
// Writes src/glyphs.ts: the outlines of the letters of ARCLIGHT in Michroma (SIL Open Font
// License 1.1, from @fontsource/michroma), so the intro needs no font at run time.
//   npm run glyphs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import opentype from 'opentype.js';

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const buf = readFileSync(require.resolve('@fontsource/michroma/files/michroma-latin-400-normal.woff'));
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
const upm = font.unitsPerEm;
const os2 = font.tables.os2;
// USE_TYPO_METRICS is set, so browsers use the typo ascender/descender for the line box.
const ascender = os2.sTypoAscender;
const descender = -os2.sTypoDescender;

const glyphs = {};
for (const ch of [...new Set('ARCLIGHT')]) {
  const g = font.charToGlyph(ch);
  // Font units, y pointing down, baseline at y = 0.
  glyphs[ch] = { advance: g.advanceWidth, d: g.getPath(0, 0, upm).toPathData(1) };
}

const out = `// Generated by scripts/gen-glyphs.mjs from Michroma (SIL Open Font License 1.1,
// Copyright 2011 The Michroma Project Authors). Do not edit.
// Outlines are in font units with y pointing down and the baseline at y = 0.

export const UNITS_PER_EM = ${upm};
/** Typo ascender / descender (the font sets USE_TYPO_METRICS), positive values. */
export const ASCENDER = ${ascender};
export const DESCENDER = ${descender};

export const GLYPHS: Readonly<Record<string, { advance: number; d: string }>> = ${JSON.stringify(glyphs, null, 2)};
`;
writeFileSync(join(here, '..', 'src', 'glyphs.ts'), out);
console.log('src/glyphs.ts written');
