import Database from 'better-sqlite3';
import { drizzle } from 'drizzle-orm/better-sqlite3';
import { migrate } from 'drizzle-orm/better-sqlite3/migrator';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import * as schema from './schema.js';

export type Db = ReturnType<typeof openDatabase>;

export function openDatabase(dbPath: string) {
  const sqlite = new Database(dbPath);
  sqlite.pragma('journal_mode = WAL');
  sqlite.pragma('foreign_keys = ON');
  sqlite.pragma('busy_timeout = 5000');

  const db = drizzle(sqlite, { schema });

  // Migrations are generated by `pnpm db:generate` into apps/api/drizzle and shipped with
  // the build, so a fresh container brings its own schema up without any tooling.
  const here = dirname(fileURLToPath(import.meta.url));
  migrate(db, { migrationsFolder: join(here, '..', '..', 'drizzle') });

  return db;
}

export { schema };
