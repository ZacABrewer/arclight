#!/usr/bin/env node
// Writes ios/App/version.xcconfig from apps/player/package.json, so the iOS app's version and
// build number follow the same rule as Android's (android/app/build.gradle):
//   ARCLIGHT_VERSION = package.json version without a pre-release suffix (CFBundleShortVersionString
//                      must be digits and dots only)
//   ARCLIGHT_BUILD   = ARCLIGHT_VERSION_CODE from the environment when set (CI uses the run number
//                      + 30000), else major*10000 + minor*100 + patch
// The file is committed with the derived values, so plain Xcode builds work without this script.
//
// Usage: node scripts/ios-version.mjs [--check] [--hook] [--out <file>]
//   --check  exit 1 if the file differs from what would be written (does not write)
//   --hook   run as package.json's capacitor:sync:after hook: do nothing unless syncing iOS
//   --out    write somewhere else (tests)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const appRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
export const XCCONFIG_PATH = join(appRoot, 'ios', 'App', 'version.xcconfig');

/** Marketing version and derived build number for a package.json version. */
export function iosVersion(pkgVersion, envCode) {
  const m = /^(\d+)\.(\d+)\.(\d+)/.exec(String(pkgVersion));
  if (!m) throw new Error(`apps/player/package.json version is not semver: ${pkgVersion}`);
  const [major, minor, patch] = [m[1], m[2], m[3]].map(Number);
  let build;
  if (envCode != null && String(envCode).trim() !== '') {
    if (!/^\d+$/.test(String(envCode).trim())) throw new Error(`ARCLIGHT_VERSION_CODE must be a whole number, got ${envCode}`);
    build = Number(String(envCode).trim());
    if (build <= 1) throw new Error(`ARCLIGHT_VERSION_CODE must be greater than 1, got ${build}`);
  } else {
    if (minor > 99 || patch > 99) throw new Error('minor and patch must stay below 100 for the derived build number');
    build = major * 10000 + minor * 100 + patch;
    if (build <= 1) throw new Error(`derived build number ${build} must be greater than 1`);
  }
  return { version: `${major}.${minor}.${patch}`, build };
}

export function xcconfigText({ version, build }) {
  return [
    '// Generated by apps/player/scripts/ios-version.mjs from apps/player/package.json (also run by',
    '// scripts/bump-version.mjs). Used by MARKETING_VERSION and CURRENT_PROJECT_VERSION in',
    '// App.xcodeproj through debug.xcconfig and release.xcconfig. Edit package.json, not this file.',
    `ARCLIGHT_VERSION = ${version}`,
    `ARCLIGHT_BUILD = ${build}`,
    '',
  ].join('\n');
}

/** Writes version.xcconfig for `pkgVersion` (default: apps/player/package.json). */
export function writeIosVersion({ pkgVersion, envCode, out = XCCONFIG_PATH } = {}) {
  const v = pkgVersion ?? JSON.parse(readFileSync(join(appRoot, 'package.json'), 'utf8')).version;
  const values = iosVersion(v, envCode);
  writeFileSync(out, xcconfigText(values));
  return values;
}

function main(argv) {
  const platform = process.env.CAPACITOR_PLATFORM_NAME;
  if (argv.includes('--hook') && platform && platform !== 'ios') return;
  const check = argv.includes('--check');
  const outIdx = argv.indexOf('--out');
  const out = outIdx >= 0 && argv[outIdx + 1] ? resolve(argv[outIdx + 1]) : XCCONFIG_PATH;
  const pkgVersion = JSON.parse(readFileSync(join(appRoot, 'package.json'), 'utf8')).version;
  const values = iosVersion(pkgVersion, process.env.ARCLIGHT_VERSION_CODE);
  if (check) {
    let current = '';
    try {
      current = readFileSync(out, 'utf8').replace(/\r\n/g, '\n');
    } catch {
      // missing file: reported below
    }
    if (current !== xcconfigText(values)) {
      console.error(`${out} is out of date; run node apps/player/scripts/ios-version.mjs`);
      process.exit(1);
    }
    console.log(`version.xcconfig ok: ${values.version} (${values.build})`);
    return;
  }
  writeFileSync(out, xcconfigText(values));
  console.log(`version.xcconfig -> ${values.version} (${values.build})`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  try {
    main(process.argv.slice(2));
  } catch (err) {
    console.error(err instanceof Error ? err.message : String(err));
    process.exit(1);
  }
}
