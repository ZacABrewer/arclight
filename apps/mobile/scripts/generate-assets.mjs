#!/usr/bin/env node
// Generates every native icon and splash image from the brand mark (design/brand):
//   Android: legacy + round launcher PNGs, adaptive icon (dark gradient background + mark
//            foreground), monochrome layer for Android 13 themed icons, notification icon,
//            Android 12 splash icon, legacy splash PNGs.
//   iOS:     1024 App Store icon with dark and tinted variants (iOS 18), splash images.
// The mark geometry is the one in design/brand/mark-color.svg (two rounded chevrons, the back
// one at 45% opacity, #2f7bff -> #6ef6ff). Output is committed; re-run after a brand change:
//   pnpm --filter @arclight/mobile assets
import { mkdirSync, readFileSync, rmSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Resvg } from '@resvg/resvg-js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const brand = join(root, '../../design/brand');
const androidRes = join(root, 'android/app/src/main/res');
const iosAssets = join(root, 'ios/App/App/Assets.xcassets');

// Sanity check that the brand mark still has the geometry used below.
const markSvg = readFileSync(join(brand, 'mark-color.svg'), 'utf8');
if (!markSvg.includes('M24,22 L52,50 L24,78') || !markSvg.includes('M48,22 L76,50 L48,78')) {
  throw new Error('design/brand/mark-color.svg changed shape: update the paths in scripts/generate-assets.mjs');
}

const BG0 = '#0b1830';
const BG1 = '#02070a';
const BLUE = '#2f7bff';
const CYAN = '#6ef6ff';
const BACK = 'M48,22 L76,50 L48,78';
const FRONT = 'M24,22 L52,50 L24,78';

/** The mark (100x100 box) scaled to `size` and centred at (cx, cy). */
function mark({ cx, cy, size, color = 'url(#mg)' }) {
  const s = size / 100;
  const t = `translate(${cx - size / 2} ${cy - size / 2}) scale(${s})`;
  const stroke = (d, op) => `<path d="${d}" fill="none" stroke="${color}" stroke-width="13" stroke-linecap="round" stroke-linejoin="round"${op ? ` opacity="${op}"` : ''}/>`;
  return `<g transform="${t}">${stroke(BACK, '.45')}${stroke(FRONT)}</g>`;
}

const defs = `<defs>
  <linearGradient id="mg" x1="0" y1="0" x2="1" y2="0"><stop offset="0" stop-color="${BLUE}"/><stop offset="1" stop-color="${CYAN}"/></linearGradient>
  <linearGradient id="bg" x1="0" y1="0" x2=".6" y2="1"><stop offset="0" stop-color="${BG0}"/><stop offset="1" stop-color="${BG1}"/></linearGradient>
</defs>`;

const svg = (w, h, body) => `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}">${defs}${body}</svg>`;

function png(svgText, width, out) {
  const data = new Resvg(svgText, { fitTo: { mode: 'width', value: width }, background: 'rgba(0,0,0,0)' }).render().asPng();
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, data);
}

// Full-bleed square icon (iOS rounds it; no transparency). Mark at the same proportion as app-icon.svg.
const squareIcon = (bg = true, color) => svg(1024, 1024, `${bg ? '<rect width="1024" height="1024" fill="url(#bg)"/>' : ''}${mark({ cx: 512, cy: 512, size: 655, ...(color ? { color } : {}) })}`);
// Legacy Android launcher: rounded tile like design/brand/app-icon.svg.
const roundedIcon = () => readFileSync(join(brand, 'app-icon.svg'), 'utf8');
const circleIcon = () => svg(100, 100, `<circle cx="50" cy="50" r="50" fill="url(#bg)"/>${mark({ cx: 50, cy: 50, size: 60 })}`);
// Adaptive foreground: 108dp canvas, content inside the 66dp safe zone.
const adaptiveForeground = () => svg(108, 108, mark({ cx: 54, cy: 54, size: 56 }));
// Splash: the mark on black, so the native splash hands off to the intro's first (black) frame.
const splash = (w, h) => svg(w, h, `<rect width="${w}" height="${h}" fill="#000"/>${mark({ cx: w / 2, cy: h / 2, size: Math.min(w, h) * 0.22 })}`);

// ---------------------------------------------------------------- Android
const densities = { mdpi: 1, hdpi: 1.5, xhdpi: 2, xxhdpi: 3, xxxhdpi: 4 };
for (const [d, k] of Object.entries(densities)) {
  png(roundedIcon(), 48 * k, join(androidRes, `mipmap-${d}/ic_launcher.png`));
  png(circleIcon(), 48 * k, join(androidRes, `mipmap-${d}/ic_launcher_round.png`));
  png(adaptiveForeground(), 108 * k, join(androidRes, `mipmap-${d}/ic_launcher_foreground.png`));
}

// Vector drawables (crisp at any size).
const vectorMark = (size, viewport, tx, scale, strokeColor) => {
  const path = (d, alpha) =>
    `        <path android:pathData="${d}" android:fillColor="#00000000" android:strokeColor="${strokeColor}"${alpha ? ` android:strokeAlpha="${alpha}"` : ''} android:strokeWidth="13" android:strokeLineCap="round" android:strokeLineJoin="round" />`;
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by apps/mobile/scripts/generate-assets.mjs from design/brand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="${size}dp" android:height="${size}dp"
    android:viewportWidth="${viewport}" android:viewportHeight="${viewport}">
    <group android:translateX="${tx}" android:translateY="${tx}" android:scaleX="${scale}" android:scaleY="${scale}">
${path(BACK, '0.45')}
${path(FRONT)}
    </group>
</vector>
`;
};
const gradientMark = (size) => {
  const path = (d, x0, x1, alpha) => `        <path android:pathData="${d}" android:fillColor="#00000000"${alpha ? ` android:strokeAlpha="${alpha}"` : ''} android:strokeWidth="13" android:strokeLineCap="round" android:strokeLineJoin="round">
            <aapt:attr name="android:strokeColor">
                <gradient android:type="linear" android:startX="${x0}" android:startY="50" android:endX="${x1}" android:endY="50">
                    <item android:offset="0" android:color="#FF2F7BFF" />
                    <item android:offset="1" android:color="#FF6EF6FF" />
                </gradient>
            </aapt:attr>
        </path>`;
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by apps/mobile/scripts/generate-assets.mjs from design/brand. Android 12+ splash icon. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="${size}dp" android:height="${size}dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <group android:translateX="13.5" android:translateY="13.5" android:scaleX="0.81" android:scaleY="0.81">
${path(BACK, 48, 76, '0.45')}
${path(FRONT, 24, 52)}
    </group>
</vector>
`;
};
const write = (file, text) => {
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, text);
};
write(join(androidRes, 'drawable/ic_launcher_monochrome.xml'), vectorMark(108, 108, 13.5, 0.81, '#FFFFFFFF'));
write(join(androidRes, 'drawable/ic_stat_arclight.xml'), vectorMark(24, 100, 4, 0.92, '#FFFFFFFF'));
write(join(androidRes, 'drawable/splash_icon.xml'), gradientMark(240));
write(
  join(androidRes, 'drawable/ic_launcher_background.xml'),
  `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by apps/mobile/scripts/generate-assets.mjs: the brand's dark gradient. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="0" android:startY="0" android:endX="64.8" android:endY="108">
                <item android:offset="0" android:color="#FF0B1830" />
                <item android:offset="1" android:color="#FF02070A" />
            </gradient>
        </aapt:attr>
    </path>
</vector>
`,
);
const adaptive = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by apps/mobile/scripts/generate-assets.mjs. Monochrome layer: Android 13+ themed icons. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
`;
write(join(androidRes, 'mipmap-anydpi-v26/ic_launcher.xml'), adaptive);
write(join(androidRes, 'mipmap-anydpi-v26/ic_launcher_round.xml'), adaptive);
write(join(androidRes, 'values/ic_launcher_background.xml'), `<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <color name="ic_launcher_background">#02070A</color>\n</resources>\n`);
// The template's default vector foreground (Capacitor logo) is replaced by the PNG mipmap.
for (const f of ['drawable-v24/ic_launcher_foreground.xml']) if (existsSync(join(androidRes, f))) rmSync(join(androidRes, f));

// Legacy splash (before Android 12): portrait/landscape per density.
const splashSizes = { mdpi: [320, 480], hdpi: [480, 800], xhdpi: [720, 1280], xxhdpi: [960, 1600], xxxhdpi: [1280, 1920] };
for (const [d, [w, h]] of Object.entries(splashSizes)) {
  png(splash(w, h), w, join(androidRes, `drawable-port-${d}/splash.png`));
  png(splash(h, w), h, join(androidRes, `drawable-land-${d}/splash.png`));
}
png(splash(480, 320), 480, join(androidRes, 'drawable/splash.png'));

// ---------------------------------------------------------------- iOS
const appIcon = join(iosAssets, 'AppIcon.appiconset');
rmSync(appIcon, { recursive: true, force: true });
png(squareIcon(true), 1024, join(appIcon, 'AppIcon-1024.png'));
png(squareIcon(false), 1024, join(appIcon, 'AppIcon-dark-1024.png')); // dark: transparent, the system adds the dark backdrop
png(squareIcon(false, '#ffffff'), 1024, join(appIcon, 'AppIcon-tinted-1024.png')); // tinted: grayscale on transparent
write(
  join(appIcon, 'Contents.json'),
  `${JSON.stringify(
    {
      images: [
        { filename: 'AppIcon-1024.png', idiom: 'universal', platform: 'ios', size: '1024x1024' },
        { appearances: [{ appearance: 'luminosity', value: 'dark' }], filename: 'AppIcon-dark-1024.png', idiom: 'universal', platform: 'ios', size: '1024x1024' },
        { appearances: [{ appearance: 'luminosity', value: 'tinted' }], filename: 'AppIcon-tinted-1024.png', idiom: 'universal', platform: 'ios', size: '1024x1024' },
      ],
      info: { author: 'xcode', version: 1 },
    },
    null,
    2,
  )}\n`,
);
const splashSet = join(iosAssets, 'Splash.imageset');
for (const f of ['splash-2732x2732.png', 'splash-2732x2732-1.png', 'splash-2732x2732-2.png']) png(splash(2732, 2732), 2732, join(splashSet, f));

console.log('Icons and splash images generated.');
